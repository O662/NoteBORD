// Generates lib/theme/tokens.g.dart from design/tokens.json.
//
//   dart run tool/gen_tokens.dart          # write the file
//   dart run tool/gen_tokens.dart --check  # exit 1 if it is out of date
//
// design/tokens.json is the only source of colors, radii and sizes. Widgets
// never hard-code hex values; they read EndlessColors via context.colors.
// test/tokens_sync_test.dart runs --check (and skips on clones without this
// tool or tokens.json, which are kept out of git).
import 'dart:convert';
import 'dart:io';

const tokensPath = 'design/tokens.json';
const outputPath = 'lib/theme/tokens.g.dart';

void main(List<String> args) {
  final json = jsonDecode(File(tokensPath).readAsStringSync()) as Map<String, dynamic>;
  final rendered = renderTokens(json);
  if (args.contains('--check')) {
    final current = File(outputPath).readAsStringSync().replaceAll('\r\n', '\n');
    if (current != rendered) {
      stderr.writeln('$outputPath is out of date. Run `dart run tool/gen_tokens.dart`.');
      exit(1);
    }
    stdout.writeln('$outputPath is up to date');
    return;
  }
  File(outputPath).writeAsStringSync(rendered);
  stdout.writeln('Wrote $outputPath');
}

String renderTokens(Map<String, dynamic> json) {
  final colors = json['colors'] as Map<String, dynamic>;
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/gen_tokens.dart from design/tokens.json. Do not edit.')
    ..writeln('// Run `dart run tool/gen_tokens.dart` after changing the tokens.')
    ..writeln()
    ..writeln("import 'package:flutter/painting.dart';")
    ..writeln()
    ..writeln("import 'colors.dart';")
    ..writeln();

  void palette(String name, Map<String, dynamic> m) {
    b.writeln('const $name = EndlessColors(');
    for (final e in m.entries) {
      if (e.key.startsWith('_')) continue;
      b.writeln('  ${e.key}: ${_color(e.value as String)},');
    }
    b.writeln(');');
    b.writeln();
  }

  palette('paperLight', colors['base'] as Map<String, dynamic>);
  palette('paperDark', colors['baseDark'] as Map<String, dynamic>);

  void colorList(String name, List<dynamic> hexes) {
    b.writeln('const $name = <Color>[');
    for (final h in hexes) {
      b.writeln('  ${_color(h as String)},');
    }
    b.writeln('];');
    b.writeln();
  }

  colorList('inkDefaults', colors['inkDefaults'] as List<dynamic>);
  colorList('extraInkDefaults', colors['extraInkDefaults'] as List<dynamic>);
  colorList('extraInkAddable', colors['extraInkAddable'] as List<dynamic>);
  b.writeln('const extraInkMax = ${colors['extraInkMax']};');
  b.writeln();

  b.writeln('/// Notebook spine and folder colors (stored colors; dark mode brightens them like ink).');
  colorList('coverColors', colors['covers'] as List<dynamic>);

  b.writeln('/// Sticky note papers. They look the same in light and dark mode.');
  colorList('stickyColors', colors['stickies'] as List<dynamic>);

  b.writeln('/// Ink color shown in dark mode, keyed by the stored (light) color.');
  b.writeln('const inkDisplayDark = <int, Color>{');
  for (final e in (colors['inkDisplayDark'] as Map<String, dynamic>).entries) {
    if (e.key.startsWith('_')) continue;
    b.writeln('  ${_hex(e.key)}: ${_color(e.value as String)},');
  }
  b.writeln('};');
  b.writeln();

  b.writeln('/// The 8 accent choices (light, dark). The first one is the theme default.');
  b.writeln('const accents = <String, (Color, Color)>{');
  for (final e in (colors['accents'] as Map<String, dynamic>).entries) {
    final v = e.value as Map<String, dynamic>;
    b.writeln("  '${e.key}': (${_color(v['light'] as String)}, ${_color(v['dark'] as String)}),");
  }
  b.writeln('};');
  b.writeln();

  b.writeln('/// Theme swatches for the Themes screen: (light, dark).');
  b.writeln('const themeSwatches = <String, (ThemeSwatch, ThemeSwatch)>{');
  for (final e in (colors['themes'] as Map<String, dynamic>).entries) {
    final v = e.value as Map<String, dynamic>;
    b.writeln("  '${e.key}': (${_swatch(v['light'] as Map<String, dynamic>)}, ${_swatch(v['dark'] as Map<String, dynamic>)}),");
  }
  b.writeln('};');
  b.writeln();

  final radius = json['radius'] as Map<String, dynamic>;
  b.writeln('abstract final class Radii {');
  for (final e in radius.entries) {
    b.writeln('  static const double ${e.key} = ${_num(e.value)};');
  }
  b.writeln('}');
  b.writeln();

  final size = json['size'] as Map<String, dynamic>;
  final dots = json['paperDots'] as Map<String, dynamic>;
  b
    ..writeln('abstract final class Sizes {')
    ..writeln('  static const double touchTarget = ${_num(size['touchTarget'])};')
    ..writeln('  static const double toolbarHeight = ${_num(size['toolbarHeight'])};')
    ..writeln('  static const Size tabletFrame = Size(${_num((size['tabletFrame'] as List)[0])}, ${_num((size['tabletFrame'] as List)[1])});')
    ..writeln('  static const double paperDotSpacing = ${_num(dots['size'])};')
    ..writeln('  static const double paperDotRadius = ${_num(dots['dotRadius'])};')
    ..writeln('}')
    ..writeln();

  final fonts = json['fonts'] as Map<String, dynamic>;
  b
    ..writeln('abstract final class FontFamilies {')
    ..writeln("  static const ui = '${fonts['ui']}';")
    ..writeln("  static const serif = '${fonts['serif']}';")
    ..writeln("  static const handwritingSample = '${fonts['handwritingSample']}';")
    ..writeln('}')
    ..writeln();

  // Type scale. Colors are applied by the widget from its palette role
  // (the token's "color" names that role, e.g. textMuted).
  b
    ..writeln('/// Type scale. Text case (e.g. uppercase section labels) is applied by the widget.')
    ..writeln('abstract final class TypeScale {');
  for (final e in (json['type'] as Map<String, dynamic>).entries) {
    final t = e.value as Map<String, dynamic>;
    final size = (t['size'] as num).toDouble();
    final family = fonts[t['font']] as String;
    final spacing = t['letterSpacing'] as String?;
    final letterSpacing = spacing == null ? null : double.parse(spacing.replaceFirst('em', '')) * size;
    b.write("  static const ${e.key} = TextStyle(fontFamily: '$family', fontSize: $size, "
        'fontWeight: FontWeight.w${t['weight']}');
    if (letterSpacing != null) b.write(', letterSpacing: ${letterSpacing.toStringAsFixed(2)}');
    b.writeln(');');
  }
  b.writeln('}');

  return b.toString();
}

String _swatch(Map<String, dynamic> m) =>
    'ThemeSwatch(bg: ${_color(m['bg'])}, side: ${_color(m['side'])}, surface: ${_color(m['surface'])}, '
    'line: ${_color(m['line'])}, text: ${_color(m['text'])}, dot: ${_color(m['dot'])}, accent: ${_color(m['accent'])})';

String _num(Object? v) => (v as num).toDouble().toString();

/// '#RRGGBB' or '#AARRGGBB' -> 0xAARRGGBB literal.
String _hex(String hex) {
  var h = hex.replaceFirst('#', '').toUpperCase();
  if (h.length == 6) h = 'FF$h';
  if (h.length != 8) throw FormatException('Bad color $hex');
  return '0x$h';
}

String _color(Object? hex) => 'Color(${_hex(hex as String)})';
